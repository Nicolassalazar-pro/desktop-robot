"""Render the official transparent Garage icon for the 240x280 LCD."""

from __future__ import annotations

from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tools" / "assets" / "official-garage" / "icon_white.png"
PREVIEW = ROOT / "tools" / "assets" / "garage_logo_240x280.png"
HEADER = ROOT / "src" / "mascot" / "garage_logo.h"

SCREEN_SIZE = (240, 280)
MAX_ICON_SIZE = (200, 170)


def format_bytes(values: bytes, columns: int = 20) -> str:
    lines = []
    for offset in range(0, len(values), columns):
        chunk = values[offset : offset + columns]
        lines.append("    " + ", ".join(f"0x{value:02X}" for value in chunk) + ",")
    return "\n".join(lines)


def main() -> None:
    icon = Image.open(SOURCE).convert("RGBA")
    icon.thumbnail(MAX_ICON_SIZE, Image.Resampling.LANCZOS)

    transparent = Image.new("RGBA", SCREEN_SIZE, (0, 0, 0, 0))
    position = (
        (SCREEN_SIZE[0] - icon.width) // 2,
        (SCREEN_SIZE[1] - icon.height) // 2,
    )
    transparent.alpha_composite(icon, position)

    preview = Image.new("RGBA", SCREEN_SIZE, (0, 0, 0, 255))
    preview.alpha_composite(transparent)
    preview.convert("RGB").save(PREVIEW)

    alpha = transparent.getchannel("A").tobytes()
    source_relative = SOURCE.relative_to(ROOT).as_posix()
    header = f"""// AUTO-GENERATED by tools/render_garage_logo.py -- do not edit by hand
// Source: {source_relative}
// Official Microsoft Garage white icon alpha mask; foreground is rendered at runtime.
#pragma once

#include <cstdint>

constexpr int16_t GARAGE_LOGO_W = {SCREEN_SIZE[0]};
constexpr int16_t GARAGE_LOGO_H = {SCREEN_SIZE[1]};

static const uint8_t GARAGE_LOGO_ALPHA[{len(alpha)}] = {{
{format_bytes(alpha)}
}};
"""
    HEADER.write_text(header, encoding="ascii")
    print(
        f"Rendered {PREVIEW.name}: icon {icon.width}x{icon.height} "
        f"at ({position[0]},{position[1]})"
    )
    print(f"Wrote {HEADER.name}: {len(alpha)} alpha pixels")


if __name__ == "__main__":
    main()
